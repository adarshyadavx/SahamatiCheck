"""`python -m sahamati_core.rules` lints the registry (CI); `--update-lock` records versions and hashes.

`--catalogue-md` prints docs/RULE_CATALOGUE.md generated from the registry; `--check-catalogue-md PATH`
fails when the committed file differs from it.
"""

import sys
from pathlib import Path

from .registry import Registry, check_lock, load_registry_uncached, write_lock

_STATIC = {"yes": "Yes", "partial": "Partial", "no_inconclusive": "No→inconclusive"}
_FAMILY = {"P": "P: Privacy policy and declaration rules", "D": "D: Personal and sensitive data rules",
           "T": "T: Third-party SDK and tracking rules", "A": "A: Permissions and Android security rules",
           "C": "C: Consent, user control and data lifecycle rules", "S": "S: Data sharing, storage and transfer rules",
           "AI": "AI: Advanced AI and consistency rules"}


def catalogue_md(reg: Registry) -> str:
    """Generated from the registry; never edit docs/RULE_CATALOGUE.md by hand."""
    en = reg.enabled()
    out = ["# Rule catalogue", "",
           "Generated by `python -m sahamati_core.rules --catalogue-md` from `backend/core/rules/registry/*.yaml`. "
           "Do not edit by hand; CI fails if it is stale.", "",
           f"**{len(reg.rules)} rules, {len(en)} enabled.** Only enabled rules run and appear in a report's `rule_runs`. "
           "A disabled rule is listed here and by `GET /v1/rules` so that nobody mistakes silence for a pass.", "",
           "Evidence: `Pol` privacy policy, `DS` Data Safety, `APK` static APK, `RT` runtime observation, `BE` backend or "
           "test account, `Meta` Play listing metadata, `Eng` the engine's own outputs. `[x]` is optional.", ""]
    for f, title in _FAMILY.items():
        rs = [r for r in reg.rules if r.family == f]
        out += [f"## {title} ({len(rs)})", "",
                "| ID | Name | Evidence | Static check | Max status (static) | Track | Phase | Report-card category | Enabled |",
                "|---|---|---|---|---|---|---|---|---|"]
        for r in rs:
            c = r.catalogue
            ev = c.evidence.replace("|", "\\|")  # not inside the f-string: Python 3.11 forbids backslashes there
            out.append(f"| {r.id} | {r.name} | {ev} | {_STATIC[c.static_check]} | "
                       f"{c.max_status_static} | {r.score_track if f != 'AI' else 'quality'} | {c.phase_note} | "
                       f"{c.report_category} | {'yes' if r.enabled else 'no'} |")
        out.append("")
    return "\n".join(out)


def main() -> int:
    reg, errors = load_registry_uncached()
    if errors or reg is None:
        print("rule registry INVALID:")
        for e in errors:
            print("  -", e)
        return 1
    if "--catalogue-md" in sys.argv:
        print(catalogue_md(reg), end="")
        return 0
    if "--check-catalogue-md" in sys.argv:
        path = Path(sys.argv[sys.argv.index("--check-catalogue-md") + 1])
        if not path.is_file() or path.read_text(encoding="utf-8") != catalogue_md(reg):
            print(f"{path} is stale; regenerate it with `python -m sahamati_core.rules --catalogue-md > {path}`")
            return 1
        print(f"{path} is up to date")
        return 0
    if "--update-lock" in sys.argv:
        print(f"wrote {write_lock(reg)}")
        return 0
    lock_errors = check_lock(reg)
    if lock_errors:
        print("rule registry lock is out of date:")
        for e in lock_errors:
            print("  -", e)
        return 1
    on = len(reg.enabled())
    print(f"rule registry OK: {len(reg.rules)} rules ({on} enabled), "
          f"{sum(len(r.tests) for r in reg.rules)} test cases, lock verified")
    return 0


if __name__ == "__main__":
    sys.exit(main())
